import math

def circulo(MEDIDA1):				#Define la funcion del aea del circulo
	return math.pi * MEDIDA1**2

def rectangulo(MEDIDA1, MEDIDA2):		#Define la funcion del area del rectangulo
	return MEDIDA1 * MEDIDA2

def triangulo(MEDIDA1, MEDIDA2):		#DEfine la funcion del area del triangulo
	return (MEDIDA1 * MEDIDA2) / 2

